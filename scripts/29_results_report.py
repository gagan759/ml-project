"""Write docs/RESULTS.md from the result files (no number in that document is typed by hand).

Sources: experiments/results/final_benchmark.json, selection_*.json, baseline_audit.json, cpu_inference.json,
experiments/cv/<task>/<recipe>/summary.json.
"""
import time

from tomatoleaf.config import EXPERIMENTS_DIR, RESULTS_DIR, ROOT
from tomatoleaf.recipes import RECIPES
from tomatoleaf.utils import load_json

OUT = ROOT / "docs" / "RESULTS.md"
TASKS = ("5class",)  # the app diagnoses five conditions; eight-condition results stay in experiments/ for the record
TASK = {"5class": "Five conditions (265 test photos)"}
CLASSICAL = "classical_5class"


def pct(v, d=1):
    return "—" if v is None else f"{100 * v:.{d}f}%"


def pts(v, d=1):
    return "—" if v is None else f"{100 * v:+.{d}f}"


def ci(pair, d=1):
    return "—" if not pair else f"{100 * pair[0]:.{d}f}–{100 * pair[1]:.{d}f}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    import sys as _sys
    bench_file = _sys.argv[_sys.argv.index("--benchmark") + 1] if "--benchmark" in _sys.argv else "final_benchmark.json"
    bench = load_json(RESULTS_DIR / bench_file)
    sel = {t: load_json(RESULTS_DIR / f"selection_{t}.json") for t in TASKS}
    audit = load_json(RESULTS_DIR / "baseline_audit.json")
    cpu = load_json(RESULTS_DIR / "cpu_inference.json") if (RESULTS_DIR / "cpu_inference.json").exists() else None
    by_key = {m["key"]: m for m in bench["models"]}
    # served models: the final-round pipelines when present (scripts/38), else the version-2 networks
    d, prev = bench.get("final_defaults") or bench["defaults"], bench["previous_defaults"]
    L = [f"# Results\n\n_Generated by `scripts/29_results_report.py` on {time.strftime('%Y-%m-%d')} from the result files in "
         "`experiments/`. Test photos were scored once, after every choice had been fixed on out-of-fold data._\n"]

    L.append("## 1. Headline: the served models vs the original study's default (same test photos)\n")
    rows = []
    for t in TASKS:
        for key in [k for k in (d[t], CLASSICAL, prev[t]) if k in by_key]:
            m = by_key[key]
            s = m["selective"]
            bold = "**" if key in (d[t], CLASSICAL) else ""
            rows.append([f"{bold}{m['name']}{bold}", t, pct(m["test"]["accuracy"]),
                         ci(m["test"]["accuracy_ci"]), pct(m["test"]["f1_macro"]), ci(m["test"]["f1_macro_ci"]),
                         f"{m['test']['ece']:.3f}", f"{pct(s['coverage'], 0)} @ {s['threshold']:.2f} → {pct(s['accuracy_kept'])}",
                         f"{bench['latency'].get(key, {}).get('median_ms', float('nan')):.0f} ms"])
    L.append(table(["Model", "Task", "Accuracy", "95% CI", "Macro-F1", "95% CI", "ECE", "Answered → accuracy", "CPU / photo"], rows))
    L.append("\n“Answered → accuracy”: share of photos the model diagnoses at its confidence threshold (the rest are "
             "“Uncertain”/“Unusual”) and its accuracy on those. CPU time: median, 8 threads, including test-time augmentation.\n")

    L.append("## 2. Paired comparisons (bootstrap over the same test leaf groups, 2,000 resamples)\n")
    rows = [[c["task"], c["a_name"], c["b_name"], pts(c["accuracy_diff"]), f"[{pts(c['accuracy_ci'][0])}, {pts(c['accuracy_ci'][1])}]",
             pts(c["f1_diff"]), f"[{pts(c['f1_ci'][0])}, {pts(c['f1_ci'][1])}]",
             "yes" if (c["f1_ci"][0] > 0 or c["f1_ci"][1] < 0) else "no"] for c in bench["comparisons"]
            if c["task"] in TASKS]
    L.append(table(["Task", "A", "B", "Δ accuracy (pts)", "95% CI", "Δ macro-F1 (pts)", "95% CI", "Macro-F1 difference reliable?"], rows))
    L.append("")

    for t in TASKS:
        L.append(f"## 3. Leaderboard — {TASK[t]}\n")
        ms = sorted((m for m in bench["models"] if m["task"] == t), key=lambda m: -m["test"]["f1_macro"])
        rows = [[m["name"] + (" ⭐" if m["key"] in (d[t], CLASSICAL) else ""), m["generation"], m["family"],
                 pct(m["test"]["accuracy"]),
                 pct(m["test"]["f1_macro"]), ci(m["test"]["f1_macro_ci"]), pct(m["test"]["f1_weighted"]), f"{m['test']['ece']:.3f}"]
                for m in ms]
        L.append(table(["Model", "Generation", "Family", "Accuracy", "Macro-F1", "95% CI", "Weighted F1", "ECE"], rows))
        L.append("")
        dm = by_key[d[t]]
        L.append(f"Per class, {dm['name']}:\n")
        L.append(table(["Class", "Precision", "Recall", "F1", "Test photos"],
                       [[p["name"], pct(p["precision"]), pct(p["recall"]), pct(p["f1"]), p["support"]] for p in dm["per_class"]]))
        L.append("")

    L.append("## 4. Cross-validation (how the upgrade was chosen — train+validation photos only)\n")
    for t in TASKS:
        L.append(f"**{TASK[t].split(' (')[0]}** — pooled out-of-fold predictions on {sel[t]['photos']} photos:\n")
        rows = []
        done = [r for r in RECIPES if (EXPERIMENTS_DIR / "cv" / t / r / "summary.json").exists()]
        sums = {r: load_json(EXPERIMENTS_DIR / "cv" / t / r / "summary.json") for r in done}
        for r in sorted(done, key=lambda r: -max(sums[r]["views"]["1"]["f1_macro"], sums[r]["views"]["8"]["f1_macro"])):
            s = sums[r]
            view = sel[t]["recipes"].get(r, {}).get("best_view", "1")
            rows.append([RECIPES[r].label + ("" if r in sel[t]["recipes"] else " (not eligible: no fold models)"),
                         pct(s["views"]["1"]["f1_macro"]), pct(s["views"]["8"]["f1_macro"]),
                         pct(s["views"]["1"]["accuracy"]), pct(s["views"]["8"]["accuracy"]),
                         f"{s['views'][view]['ece_calibrated']:.3f}", f"{s['train_minutes_total']:.0f}"])
        L.append(table(["Recipe", "Macro-F1", "Macro-F1 (TTA)", "Accuracy", "Accuracy (TTA)", "ECE (calibrated)", "GPU min (5 folds)"], rows))
        top = sel[t]["candidates"][:6]
        L.append("\nBest candidates (ensembles average calibrated probabilities of whole fold ensembles):\n")
        L.append(table(["Candidate", "OOF macro-F1", "95% CI", "OOF accuracy", "Est. CPU ms"],
                       [[c["key"], pct(c["oof"]["f1_macro"]), ci(c["oof"]["f1_macro_ci"]), pct(c["oof"]["accuracy"]),
                         f"{c['latency_ms']:.0f}"] for c in top]))
        L.append(f"\nChosen: **{sel[t]['chosen']['key']}**. Rule: {sel[t]['selection_rule']}\n")

    L.append("**Screening on fold 0** (every recipe tried, including those not run on all folds):\n")
    rows = []
    for t in TASKS:
        for r in RECIPES:
            p = EXPERIMENTS_DIR / "cv" / t / r / "fold0.json"
            if p.exists():
                f0 = load_json(p)
                full = (EXPERIMENTS_DIR / "cv" / t / r / "summary.json").exists()
                rows.append([t, RECIPES[r].label, pct(f0["held_1view"]["f1_macro"]), pct(f0["held_tta8"]["f1_macro"]),
                             pct(f0["held_1view"]["accuracy"]), pct(f0["held_tta8"]["accuracy"]), "5 folds" if full else "fold 0 only"])
    L.append(table(["Task", "Recipe", "Macro-F1", "Macro-F1 (TTA)", "Accuracy", "Accuracy (TTA)", "Run"], rows))
    L.append("")

    L.append("## 5. Preprocessing audit (original deployed 5-class model, validation photos)\n")
    a = audit["models"]["ensemble_5class"]
    names = {"clean": "Dataset file (reference)", "upload_p3_original_path": "Phone photo, Display P3 — original upload path",
             "upload_p3_new_path": "Phone photo, Display P3 — new upload path", "upload_srgb_original_path": "sRGB photo — original upload path",
             "upload_srgb_new_path": "sRGB photo — new upload path"}
    L.append(table(["Input", "Accuracy", "Macro-F1", "Predictions changed vs reference"],
                   [[names[k], pct(a[k]["accuracy"]), pct(a[k]["f1_macro"]), pct(a[k].get("flip_rate", 0.0))] for k in names if k in a]))
    L.append("\nAll original models (share of validation predictions that change):\n")
    keys = ["upload_p3_original_path", "upload_p3_new_path", "upload_srgb_original_path", "upload_srgb_new_path", "jpeg_q50", "half_resolution"]
    L.append(table(["Model"] + [k.replace("upload_", "").replace("_", " ") for k in keys],
                   [[m] + [pct(v[k]["flip_rate"]) for k in keys] for m, v in audit["models"].items()]))
    dih = {k: v["dihedral_views"] for k, v in audit["models"].items() if "dihedral_views" in v}
    if dih:
        L.append("\nRotation consistency of the original single-view models (8 flips/rotations of each validation photo):\n")
        L.append(table(["Model", "Photos where all 8 views agree", "Accuracy per view (min–max)"],
                       [[k, pct(v["all_8_views_agree"]), f"{pct(min(v['per_view_accuracy']))}–{pct(max(v['per_view_accuracy']))}"]
                        for k, v in dih.items()]))
    L.append("")

    L.append("## 6. Robustness on the test photos: share of predictions that change\n")
    for t in TASKS:
        rb = bench["robustness"][t]
        ks = list(next(iter(rb.values())).keys())
        L.append(f"**{TASK[t].split(' (')[0]}**\n")
        L.append(table(["Change"] + [by_key[k]["name"] for k in rb], [[k] + [pct(rb[m][k]["flip_rate"]) for m in rb] for k in ks]))
        L.append("")

    L.append("## 7. “Unusual image” (out-of-distribution) check\n")
    rows = []
    for t in TASKS:
        o = sel[t]["ood"]
        e = o["evaluation_oof"][o["method"]]
        tb = bench["ood"][t]
        rows.append([t, o["method"], f"{e['auroc_select']:.3f}", pct(tb["flagged_in"]), pct(tb.get("flagged_near")),
                     pct(tb["flagged_far_B"]), pct(tb.get("no_diagnosis_near")), pct(tb["no_diagnosis_far_B"])])
    L.append(table(["Task", "Score", "OOF AUROC (choice)", "Test in-scope flagged", "Out-of-scope conditions flagged",
                    "Non-leaf images (held-out half) flagged", "Out-of-scope: no diagnosis", "Non-leaf: no diagnosis"], rows))
    L.append("\n“No diagnosis” counts either flag: “Unusual image” or “Uncertain”.\n")

    if cpu:
        L.append("## 8. CPU inference options (one fold model, deployed number of views, 8 threads)\n")
        rows = [[r["recipe"], r["views"], f"{r['timings_ms']['8']['torch_eager']:.0f}", f"{r['timings_ms']['8']['torch_channels_last']:.0f}",
                 f"{r['timings_ms']['8']['onnxruntime']:.0f}", f"{r['max_abs_prob_diff_onnx_vs_torch']:.1e}"] for r in cpu["results"]]
        L.append(table(["Recipe", "Views", "PyTorch ms", "channels-last ms", "ONNX Runtime ms", "max |Δp| ONNX vs PyTorch"], rows))
        L.append("")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
